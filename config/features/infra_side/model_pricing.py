"""Per-model token pricing and the token-budget warning threshold.

Prices are USD per 1,000,000 tokens and are estimates used only for budget
warnings, never for billing.

The table is USER-CONFIGURABLE: ``.models`` carries a ``MODEL_PRICING_TABLE``
JSON object (seeded from ``.models.example``) which ``config/models_settings.py``
hydrates into the environment. The module therefore hardcodes no concrete model
price; only :data:`_FALLBACK_DEFAULT` remains for a missing/invalid config.

Lookup order is:

1. the user table (exact model name, then the part after a ``/`` prefix);
2. the local litellm ``model_cost`` cache (``src/data/litellm_prices.json``,
   generated by ``scripts/sync_litellm_prices.py``);
3. the user table's ``_default`` entry (or the code fallback).
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import TypedDict

from loguru import logger

from config.path import SRC_DIR


class ModelPricingConfig(TypedDict):
    """Model price table plus the budget warning threshold (fraction of budget)."""

    model_pricing_per_m_tokens: dict[str, dict[str, float]]
    budget_warn_threshold: float


#: Final fallback only when the user table is missing/invalid. Kept in code
#: deliberately: a broken configuration must still produce a number.
_FALLBACK_DEFAULT: dict[str, float] = {"input": 0.5, "output": 1.5}


def _normalized_entry(value: object) -> dict[str, float] | None:
    """Validate one price entry ``{"input": x, "output": y[, "cache_read", "cache_write"]}``.

    The two cache prices are OPTIONAL and mean "USD per 1M cached tokens": a
    read of a cached prefix (~0.1x input on Anthropic) and a write into the
    cache (~1.25x for the 5-minute TTL, ~2x for 1 hour). Omitting them prices
    cached tokens at the plain input rate, which is exactly the pre-existing
    behaviour — an existing table gains accuracy only when the operator adds
    the fields, never a silently invented discount.
    """
    if not isinstance(value, dict):
        return None
    try:
        input_price = float(str(value.get("input")))
        output_price = float(str(value.get("output")))
    except (TypeError, ValueError):
        return None
    if input_price < 0 or output_price < 0:
        return None
    entry: dict[str, float] = {"input": input_price, "output": output_price}
    for key in ("cache_read", "cache_write"):
        raw = value.get(key)
        if raw is None:
            continue
        try:
            price = float(str(raw))
        except (TypeError, ValueError):
            continue
        if price >= 0:
            entry[key] = price
    return entry


def _load_pricing_table(raw: str | None = None) -> dict[str, dict[str, float]]:
    """Parse the user's ``MODEL_PRICING_TABLE`` JSON string.

    A missing/blank/malformed value returns only ``_default``. Valid entries
    are kept; an invalid entry is dropped rather than failing the whole table.
    """
    text = (raw if raw is not None else os.getenv("MODEL_PRICING_TABLE", "")).strip()
    if not text:
        return {"_default": dict(_FALLBACK_DEFAULT)}
    try:
        parsed = json.loads(text)
    except (TypeError, ValueError):
        return {"_default": dict(_FALLBACK_DEFAULT)}
    if not isinstance(parsed, dict):
        return {"_default": dict(_FALLBACK_DEFAULT)}
    table: dict[str, dict[str, float]] = {}
    for name, entry in parsed.items():
        normalized = _normalized_entry(entry)
        if normalized is not None:
            table[str(name)] = normalized
    table.setdefault("_default", dict(_FALLBACK_DEFAULT))
    return table


def _load_litellm_prices() -> dict[str, dict[str, float]]:
    """Load the local litellm model-cost cache (per-token → per-1M)."""
    cache_path = Path(SRC_DIR) / "data" / "litellm_prices.json"
    if not cache_path.is_file():
        return {}
    try:
        data = json.loads(cache_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        logger.warning("litellm prices load failed: {}", exc)
        return {}
    if not isinstance(data, dict):
        return {}
    cache: dict[str, dict[str, float]] = {}
    for model_name, entry in data.items():
        if model_name == "sample_spec" or not isinstance(entry, dict):
            continue
        try:
            input_price = float(entry["input_cost_per_token"])
            output_price = float(entry["output_cost_per_token"])
        except (KeyError, TypeError, ValueError):
            continue
        if input_price < 0 or output_price < 0:
            continue
        price = {"input": input_price * 1_000_000, "output": output_price * 1_000_000}
        cache[str(model_name)] = price
        # litellm spells some models "provider/model"; let a bare name hit too.
        bare = str(model_name).rsplit("/", 1)[-1]
        cache.setdefault(bare, price)
    return cache


_LITELLM_CACHE: dict[str, dict[str, float]] = _load_litellm_prices()


MODEL_PRICING: ModelPricingConfig = {
    "model_pricing_per_m_tokens": _load_pricing_table(),
    "budget_warn_threshold": 0.80,
}


def resolve_model_pricing(model_name: str | None) -> dict[str, float]:
    """User table → litellm cache → user ``_default`` / code fallback."""
    table = MODEL_PRICING["model_pricing_per_m_tokens"]
    name = (model_name or "").strip()
    if name:
        if name in table:
            return table[name]
        bare = name.rsplit("/", 1)[-1]
        if bare in table:
            return table[bare]
        if name in _LITELLM_CACHE:
            return _LITELLM_CACHE[name]
        if bare in _LITELLM_CACHE:
            return _LITELLM_CACHE[bare]
    return table.get("_default", _FALLBACK_DEFAULT)


__all__ = [
    "MODEL_PRICING",
    "ModelPricingConfig",
    "resolve_model_pricing",
]
